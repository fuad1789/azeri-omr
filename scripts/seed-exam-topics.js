async function seedExamTopics() {
  const uri = process.env.MONGODB_URI || 'mongodb://localhost:27017/azeriedu_local';
  
  try {
    const client = new MongoClient(uri);
    await client.connect();
    console.log('MongoDB-yə qoşuldu');

    const db = client.db();
    const topicsCollection = db.collection('examtopics');

    // Əvvəlcə mövcud mövzuları təmizlə
    await topicsCollection.deleteMany({});
    console.log('Köhnə mövzular təmizləndi');

    // Yeni mövzuları əlavə et
    const result = await topicsCollection.insertMany(examTopics);
    console.log(`${result.insertedCount} mövzu uğurla əlavə edildi`);

    await client.close();
    console.log('Bağlandı');
  } catch (error) {
    console.error('Xəta:', error);
    process.exit(1);
  }
}

